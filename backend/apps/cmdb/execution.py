"""Authorized CMDB probes using the single ops executor."""

import shutil
import tempfile

from apps.ops.contracts import ExecutionPlan
from apps.ops.executor import AnsibleExecutor
from apps.ops.workflow.inventory import build_inventory
from .credentials import DatabaseCredentialProvider
from .targets import resolve_targets


def execute_asset_module(*, actor, host_id, module, module_args="", timeout=60, on_event):
    from apps.jobs.execution.plan_builder import prepare_host_gateway_execution

    targets = resolve_targets(actor=actor, host_ids=[host_id], group_ids=[])
    hosts, group_vars, gateway_directory = prepare_host_gateway_execution(targets)
    gateway_directory = gateway_directory or tempfile.mkdtemp(prefix="devops-probe-")
    try:
        plan = ExecutionPlan(
            run_id=0, node_run_id=0, command_type="module", target_hosts=targets,
            inventory=build_inventory(
                hosts,
                group_vars,
                credential_provider=DatabaseCredentialProvider(gateway_directory),
            ),
            playbook=[], extra_vars={},
            env_vars={}, private_data_dir=gateway_directory, timeout_seconds=timeout,
            module=module, module_args=module_args,
        )
        return AnsibleExecutor().execute(plan, on_event, lambda: False)
    finally:
        # This path is generated by prepare_host_gateway_execution, never supplied by clients.
        if gateway_directory:
            shutil.rmtree(gateway_directory, ignore_errors=True)
